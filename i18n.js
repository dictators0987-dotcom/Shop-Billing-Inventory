let currentLanguage = 'en';

function readStoredLanguage() {
  try {
    return localStorage.getItem(I18N_STORAGE_KEY);
  } catch (error) {
    return null;
  }
}

// Currency is independent of language - a shop can bill in US dollars while reading
// the interface in Arabic. Only the symbol is configurable; amounts are always
// formatted the same way (symbol, space, number), matching the app's original "Rs."
// style instead of guessing each currency's native placement convention.
const CURRENCY_STORAGE_KEY = 'shop_inventory_currency_v1';
const CURRENCIES = {
  PKR: 'Rs.',
  INR: '₹',
  USD: '$',
  EUR: '€',
  GBP: '£',
  AED: 'د.إ',
  SAR: '﷼',
  BDT: '৳',
};
let currentCurrency = 'PKR';

function readStoredCurrency() {
  try {
    return localStorage.getItem(CURRENCY_STORAGE_KEY);
  } catch (error) {
    return null;
  }
}

function getCurrency() {
  return currentCurrency;
}

function getCurrencySymbol() {
  return CURRENCIES[currentCurrency] || CURRENCIES.PKR;
}

function t(key, params) {
  const dict = I18N[currentLanguage] || I18N.en;
  let text = dict[key] ?? I18N.en[key] ?? key;
  const merged = { currency: getCurrencySymbol(), ...params };
  Object.keys(merged).forEach((name) => {
    text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), merged[name]);
  });
  return text;
}

function getLanguage() {
  return currentLanguage;
}

function getDateLocale() {
  return LOCALE_MAP[currentLanguage] || 'en-US';
}

function translateStaticUI() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
  document.title = t('documentTitle');
}

function applyLanguage(name) {
  currentLanguage = Object.hasOwn(I18N, name) ? name : 'en';
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = RTL_LANGUAGES.includes(currentLanguage) ? 'rtl' : 'ltr';
  translateStaticUI();
  return currentLanguage;
}

function applyCurrency(code) {
  currentCurrency = Object.hasOwn(CURRENCIES, code) ? code : 'PKR';
  translateStaticUI();
  return currentCurrency;
}

applyLanguage(new URLSearchParams(window.location.search).get('lang') || readStoredLanguage());
applyCurrency(new URLSearchParams(window.location.search).get('currency') || readStoredCurrency());
